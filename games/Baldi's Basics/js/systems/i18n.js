  function init() {
    const saves = Saves.load();
    const want = saves.lang || (navigator.language || 'en').toLowerCase();
    if (want.startsWith('zh')) lang = 'zh';
    else if (want.startsWith('ja')) lang = 'ja';
    else lang = 'en';
  }

  function setLang(l) {
    if (!DICT[l]) return;
    lang = l;
    const saves = Saves.load();
    saves.lang = l;
    Saves.save(saves);
  }

  function t(key, params) {
    let s = (DICT[lang] && DICT[lang][key]) || DICT.en[key] || key;
    if (params) {
      for (const k of Object.keys(params)) {
        s = s.split(`{${k}}`).join(String(params[k]));
      }
    }
    return s;
  }

  return { init, setLang, t, get lang() { return lang; } };
